'use strict'

/**
 * 注入自建评论组件 / 个人中心 / 导航头像，并适配 swup 单页跳转
 *
 * Hexo 8 的 scripts 加载方式和 6/7 不同：它把脚本体直接放进
 * `(async function(exports, require, module, __filename, __dirname, hexo){ ... })`
 * 里执行，`hexo` 是参数；**不会**调用 `module.exports = function (hexo) {}`。
 * 所以这里必须写裸脚本。
 *
 * swup 开启后（theme.global.single_page: true），只有 #swup 容器内的 DOM 会被替换，
 * body_end 注入的节点和脚本不会重跑。因此：
 *   - 评论挂载点、个人中心脚本、导航头像全部改为「按需 + 每次页面切换后重建」；
 *   - 评论组件暴露 window.__mountKamiComments，切页后直接复用，不重复下载；
 *   - /about 及其内部链接加 data-no-swup，保持整页刷新（该页有全屏自定义布局和特效）。
 */

const bootScript = [
  '<script>',
  '(function () {',
  '  var GA_ID = "G-XMPJXEFLKH";',
  '',
  '  // ---------- 1. 关于页保持整页刷新 ----------',
  '  var NO_SWUP = /^\\/(about|login)(\\/|$)/;',
  '  function markNoSwup() {',
  '    var isSelf = NO_SWUP.test(location.pathname);',
  '    var links = document.querySelectorAll("a[href]");',
  '    for (var i = 0; i < links.length; i++) {',
  '      var a = links[i];',
  '      var url = null;',
  '      try { url = new URL(a.getAttribute("href"), location.origin); } catch (e) { continue; }',
  '      if (url.origin !== location.origin) continue;',
  '      if (isSelf || NO_SWUP.test(url.pathname)) {',
  '        a.setAttribute("data-no-swup", "");',
  '      }',
  '    }',
  '  }',
  '',
  '  // ---------- 2. 登录后导航头像 ----------',
  '  function applyNavAvatar() {',
  '    var token = localStorage.getItem("token");',
  '    var user = null;',
  '    try { user = JSON.parse(localStorage.getItem("user") || "null"); } catch (e) { user = null; }',
  '    if (!token || !user) return;',
  '    var name = user.nickname || user.username || "我";',
  '    var initial = String(name).slice(0, 1).toUpperCase();',
  '    var arrived = false;',
  '    try { arrived = sessionStorage.getItem("blog-login-fly") === "1"; } catch (e) { arrived = false; }',
  '    function fallback() {',
  '      var span = document.createElement("span");',
  '      span.className = "nav-user-avatar fallback not-markdown" + (arrived ? " nav-avatar-arrive" : "");',
  '      span.textContent = initial;',
  '      return span;',
  '    }',
  '    var links = document.querySelectorAll(\'a[href="/login/"]\');',
  '    for (var i = 0; i < links.length; i++) {',
  '      var link = links[i];',
  '      link.setAttribute("href", "/profile/");',
  '      link.className += " nav-avatar-link";',
  '      link.setAttribute("aria-label", name + " 的个人中心");',
  '      link.setAttribute("title", "个人中心");',
  '      link.innerHTML = "";',
  '      if (user.avatar) {',
  '        var img = document.createElement("img");',
  '        img.src = user.avatar;',
  '        img.alt = name;',
  '        img.className = "nav-user-avatar not-markdown" + (arrived ? " nav-avatar-arrive" : "");',
  '        img.onerror = function () { this.replaceWith(fallback()); };',
  '        link.appendChild(img);',
  '      } else {',
  '        link.appendChild(fallback());',
  '      }',
  '    }',
  '    if (arrived) { try { sessionStorage.removeItem("blog-login-fly"); } catch (e) {} }',
  '  }',
  '',
  '  // ---------- 3. 按需插入样式 / 脚本 ----------',
  '  function ensureCss(href) {',
  '    if (document.querySelector(\'link[data-kami="\' + href + \'"]\')) return;',
  '    var l = document.createElement("link");',
  '    l.rel = "stylesheet";',
  '    l.href = href;',
  '    l.setAttribute("data-kami", href);',
  '    document.head.appendChild(l);',
  '  }',
  '',
  '  function isPostPage() {',
  '    return !!document.querySelector(".article-nav, .post-copyright-info, .main-content-body article");',
  '  }',
  '',
  '  // ---------- 4. 评论区 ----------',
  '  function bootComments() {',
  '    if (!isPostPage()) return;',
  '    var root = document.getElementById("kami-comments-root");',
  '    if (!root) {',
  '      root = document.createElement("div");',
  '      root.id = "kami-comments-root";',
  '      var anchor = document.querySelector(".article-nav") || document.querySelector(".post-copyright-info");',
  '      if (anchor && anchor.parentNode) {',
  '        anchor.parentNode.insertBefore(root, anchor.nextSibling);',
  '      } else {',
  '        var art = document.querySelector("article");',
  '        if (!art || !art.parentNode) return;',
  '        art.parentNode.insertBefore(root, art.nextSibling);',
  '      }',
  '    }',
  '    ensureCss("/assets/kami-comments/comment-widget.css");',
  '    if (window.__mountKamiComments) {',
  '      window.__mountKamiComments();',
  '      return;',
  '    }',
  '    if (document.querySelector(\'script[data-kami-comments]\')) return;',
  '    var s = document.createElement("script");',
  '    s.type = "module";',
  '    s.src = "/assets/kami-comments/comment-widget.js";',
  '    s.setAttribute("data-kami-comments", "");',
  '    s.addEventListener("load", function () {',
  '      if (window.__mountKamiComments) window.__mountKamiComments();',
  '    });',
  '    document.head.appendChild(s);',
  '  }',
  '',
  '  // ---------- 4.5 留言板（便利贴墙） ----------',
  '  function bootCommentsWall() {',
  '    if (location.pathname.replace(/\\/+$/, "") !== "/comments") return;',
  '    if (!document.getElementById("commentsPage")) return;',
  '    if (window.__kamiWallInit) { window.__kamiWallInit(); return; }',
  '    if (document.querySelector(\'script[data-kami-wall]\')) return;',
  '    var s = document.createElement("script");',
  '    s.src = "/assets/kami-comments/wall.js";',
  '    s.setAttribute("data-kami-wall", "");',
  '    s.addEventListener("load", function () { if (window.__kamiWallInit) window.__kamiWallInit(); });',
  '    document.head.appendChild(s);',
  '  }',
  '',
  '  // ---------- 5. 个人中心 ----------',
  '  function bootProfile() {',
  '    var p = location.pathname.replace(/\\/+$/, "");',
  '    if (p !== "/profile") return;',
  '    ensureCss("/assets/blog-profile/profile.css");',
  '    // 已加载过：直接重挂（swup 可能已经把旧挂载点换掉）',
  '    if (window.__mountKamiProfile) { window.__mountKamiProfile(); return; }',
  '    if (document.querySelector(\'script[data-kami-profile]\')) return;',
  '    var s = document.createElement("script");',
  '    s.type = "module";',
  '    s.src = "/assets/blog-profile/profile.js";',
  '    s.setAttribute("data-kami-profile", "");',
  '    s.addEventListener("load", function () { if (window.__mountKamiProfile) window.__mountKamiProfile(); });',
  '    document.body.appendChild(s);',
  '  }',
  '',
  '  // ---------- 6. Google Analytics 延迟加载（不占首屏） ----------',
  '  function bootGA() {',
  '    if (window.__kamiGAInjected) return;',
  '    window.__kamiGAInjected = true;',
  '    setTimeout(function () {',
  '      window.dataLayer = window.dataLayer || [];',
  '      window.gtag = function () { window.dataLayer.push(arguments); };',
  '      window.gtag("js", new Date());',
  '      window.gtag("config", GA_ID);',
  '      var s = document.createElement("script");',
  '      s.async = true;',
  '      s.src = "https://www.googletagmanager.com/gtag/js?id=" + GA_ID;',
  '      document.head.appendChild(s);',
  '    }, 3000);',
  '  }',
  '',
  '  function boot() {',
  '    markNoSwup();',
  '    applyNavAvatar();',
  '    bootComments();',
  '    bootCommentsWall();',
  '    bootProfile();',
  '    bootGA();',
  '  }',
  '',
  '  if (document.readyState === "loading") {',
  '    document.addEventListener("DOMContentLoaded", boot);',
  '  } else {',
  '    boot();',
  '  }',
  '  window.addEventListener("load", boot);',
  '',
  '  // swup 的 page:view 在内容替换完成后触发；同时兼容主题的 pjax / pageSwitch 事件',
  '  ["swup:page:view", "redefine:pageSwitch", "pjax:complete", "pjax:success"].forEach(function (name) {',
  '    document.addEventListener(name, function () { setTimeout(boot, 0); });',
  '  });',
  '})();',
  '</script>'
].join('\n')

const navCss = [
  '<style>',
  '.nav-user-avatar{width:30px;height:30px;border-radius:50%;object-fit:cover;display:block;border:2px solid rgba(255,255,255,.88);box-shadow:0 3px 10px rgba(0,0,0,.18);}',
  '.nav-user-avatar.fallback{display:flex;align-items:center;justify-content:center;background:linear-gradient(135deg,#6366f1,#8b5cf6);color:#fff;font-size:13px;font-weight:800;}',
  '.navbar a[href="/profile/"].nav-avatar-link,.drawer-navbar-item a[href="/profile/"].nav-avatar-link{display:inline-flex;align-items:center;justify-content:center;padding:0 6px;line-height:1;}',
  '.navbar a[href="/profile/"].nav-avatar-link i,.drawer-navbar-item a[href="/profile/"].nav-avatar-link i{display:none;}',
  '@keyframes navAvatarArrive{0%{transform:scale(.38);opacity:0}65%{transform:scale(1.12);opacity:1}100%{transform:scale(1);opacity:1}}',
  '.nav-user-avatar.nav-avatar-arrive{animation:navAvatarArrive .6s cubic-bezier(.2,.9,.3,1.3) both;}',
  '</style>'
].join('')

hexo.extend.injector.register('head_end', navCss)
hexo.extend.injector.register('body_end', bootScript)
